const LOCAL_KEY_PREFIX = 'get_me_a_job_cache_v32_';
const INVALID_DOMAINS = ['builtin.com/job/', 'wellfound.com/job/', 'weworkremotely.com/job/', 'remoterocketship.com/job/', 'workatastartup.com/jobs/'];

function isValidJob(job: Job): boolean {
  const url = job.jobUrl;
  if (!url) return false;
  // block generic homepage landing boards without exact posting path
  if (url === 'https://jobs.lever.co/palantir' || url === 'https://boards.greenhouse.io/splice') return false;
  return !INVALID_DOMAINS.some(d => url.includes(d));
}

function mergeMissingJobs(existing: Job[]): Job[] {
  const validExisting = existing.filter(isValidJob);
  const ids = new Set(validExisting.map(j => j.id));
  const missing = INITIAL_JOBS.filter(j => !ids.has(j.id));
  return [...validExisting, ...missing];
}

